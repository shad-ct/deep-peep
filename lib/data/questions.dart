class DataService {
  static List<Question> get allQuestions {
    List<Question> questions = [];

    for (var entry in _rawData.entries) {
      final category = entry.key;
      final textsEn = entry.value;
      final textsMl = rawDataMl[category] ?? [];

      for (int i = 0; i < textsEn.length; i++) {
        questions.add(Question(
          id: '${category.name}_$i',
          text: textsEn[i],
          textMl: i < textsMl.length ? textsMl[i] : null,
          category: category,
        ));
      }
    }
    return questions;
  }

  static List<Question> getQuestionsForCategory(Category category) {
    return allQuestions.where((q) => q.category == category).toList();
  }
